/**
 * 团队知识条目标识键自动生成与校验单测（HC-230）。
 */
import assert from "node:assert/strict"
import { test } from "node:test"
import { resolveKnowledgeTermKey } from "../src/renderer/features/collaboration/knowledge/knowledge-key.ts"

const CONTRACT_TERM_KEY_RE = /^[a-z0-9][a-z0-9._-]{0,63}$/

test("留空自定义标识键时，纯中文标题自动生成满足后端契约的稳定 kb-<hash> 键", () => {
  const first = resolveKnowledgeTermKey("《除法安全规范》", "")
  const second = resolveKnowledgeTermKey("《除法安全规范》", "   ")
  assert.equal(first.valid, true)
  assert.equal(first.autoGenerated, true)
  assert.equal(first.error, undefined)
  assert.match(first.termKey, /^kb-[0-9a-f]{8}$/)
  assert.match(first.termKey, CONTRACT_TERM_KEY_RE)
  assert.equal(first.termKey, second.termKey)
})

test("中英混排标题留空标识键时，提取英文 slug 并附加短摘要", () => {
  const resolved = resolveKnowledgeTermKey("Divide by Zero 除零保护规范", "")
  assert.equal(resolved.valid, true)
  assert.equal(resolved.autoGenerated, true)
  assert.ok(resolved.termKey.startsWith("divide-by-zero-"))
  assert.match(resolved.termKey, CONTRACT_TERM_KEY_RE)
})

test("标题和标识键同时为空时不合法", () => {
  const empty = resolveKnowledgeTermKey("   ", "")
  assert.equal(empty.valid, false)
  assert.equal(empty.termKey, "")
  assert.equal(empty.error, undefined)
})

test("自定义标识键校验合法输入并拦截中文/空格/大写等非法输入", () => {
  const valid = resolveKnowledgeTermKey("任意标题", "divide_by.zero-v1")
  assert.deepEqual(valid, {
    termKey: "divide_by.zero-v1",
    autoGenerated: false,
    valid: true,
  })

  for (const invalidInput of ["《除法安全规范》", "DivideZero", "-leading-dash", "has space"]) {
    const bad = resolveKnowledgeTermKey("《除法安全规范》", invalidInput)
    assert.equal(bad.valid, false)
    assert.equal(bad.autoGenerated, false)
    assert.ok(bad.error && bad.error.includes("标识键仅支持"))
  }
})
