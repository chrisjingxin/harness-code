/**
 * 团队知识条目标识键（termKey）生成与校验工具。
 *
 * 【功能定义】
 * 后端契约要求 knowledge.termKey 必须匹配 `^[a-z0-9][a-z0-9._-]{0,63}$`（纯英文数字短标）。
 * 用户新建知识时通常直接填中文标题而不知道什么是“术语键”；本工具在用户留空时
 * 根据标题稳定生成合法的短标识，并在用户手动填写非法字符时给出通俗明确的提示。
 */

const TERM_KEY_PATTERN = /^[a-z0-9][a-z0-9._-]{0,63}$/
const TERM_KEY_MAX_LENGTH = 64

export type ResolvedKnowledgeTermKey = {
  readonly termKey: string
  readonly autoGenerated: boolean
  readonly valid: boolean
  readonly error?: string
}

/** 计算 UTF-16 字符串的 32 位 FNV-1a 十六进制摘要（固定 8 位小写十六进制）。 */
function fnv1aHex(text: string): string {
  let hash = 0x811c9dc5
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i)
    hash = Math.imul(hash, 0x01000193)
  }
  return (hash >>> 0).toString(16).padStart(8, "0")
}

/**
 * 解析并校验知识条目的 `termKey`：
 * - `customTermKey` 非空时严格按后端规范校验，失败返回通俗中文提示；
 * - `customTermKey` 留空时基于 `title` 自动生成满足契约的唯一短标识。
 */
export function resolveKnowledgeTermKey(
  title: string,
  customTermKey: string,
): ResolvedKnowledgeTermKey {
  const custom = customTermKey.trim()
  if (custom) {
    if (!TERM_KEY_PATTERN.test(custom)) {
      return {
        termKey: "",
        autoGenerated: false,
        valid: false,
        error: "标识键仅支持小写英文字母、数字及 . _ -（留空可根据标题自动生成）",
      }
    }
    return {
      termKey: custom,
      autoGenerated: false,
      valid: true,
    }
  }

  const trimmedTitle = title.trim()
  if (!trimmedTitle) {
    return {
      termKey: "",
      autoGenerated: true,
      valid: false,
    }
  }

  const hash8 = fnv1aHex(trimmedTitle)
  const asciiTokens = trimmedTitle.toLowerCase().match(/[a-z0-9]+/g)
  if (asciiTokens && asciiTokens.length > 0) {
    const slug = asciiTokens.join("-").slice(0, 48).replace(/-+$/g, "")
    if (slug) {
      const candidate = `${slug}-${hash8.slice(0, 6)}`.slice(0, TERM_KEY_MAX_LENGTH)
      if (TERM_KEY_PATTERN.test(candidate)) {
        return {
          termKey: candidate,
          autoGenerated: true,
          valid: true,
        }
      }
    }
  }

  return {
    termKey: `kb-${hash8}`,
    autoGenerated: true,
    valid: true,
  }
}
